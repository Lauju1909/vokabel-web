class I18nManager {
  static KEY_LANG = "vokabelstar_ui_lang";

  static detectSystemLanguage() {
    const rawLangs = navigator.languages || [navigator.language || navigator.userLanguage || "en"];
    for (const raw of rawLangs) {
      const code = String(raw).toLowerCase().split("-")[0];
      if (I18N_TRANSLATIONS[code]) {
        return code;
      }
    }
    return "en";
  }

  static getActiveLanguage() {
    const saved = localStorage.getItem(this.KEY_LANG);
    if (saved && saved !== "auto" && I18N_TRANSLATIONS[saved]) {
      return saved;
    }
    return this.detectSystemLanguage();
  }

  static getSavedPreference() {
    return localStorage.getItem(this.KEY_LANG) || "auto";
  }

  static setLanguage(langCode) {
    localStorage.setItem(this.KEY_LANG, langCode);
    this.applyLanguage();
  }

  static t(key, params = {}) {
    const currentLang = this.getActiveLanguage();
    const dict = I18N_TRANSLATIONS[currentLang] || I18N_TRANSLATIONS["en"] || I18N_TRANSLATIONS["de"];
    const fallbackDict = I18N_TRANSLATIONS["de"] || I18N_TRANSLATIONS["en"];

    let text = dict[key] !== undefined ? dict[key] : (fallbackDict[key] !== undefined ? fallbackDict[key] : key);

    // Replace {placeholder}
    Object.keys(params).forEach(pKey => {
      text = text.replace(new RegExp(`\\{${pKey}\\}`, "g"), params[pKey]);
    });

    return text;
  }

  static applyLanguage() {
    const lang = this.getActiveLanguage();
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

    // Update all elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = this.t(key);
      if (translation) {
        el.textContent = translation;
      }
    });

    // Update elements with data-i18n-aria
    document.querySelectorAll("[data-i18n-aria]").forEach(el => {
      const key = el.getAttribute("data-i18n-aria");
      const translation = this.t(key);
      if (translation) {
        el.setAttribute("aria-label", translation);
      }
    });

    // Update elements with data-i18n-placeholder
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      const translation = this.t(key);
      if (translation) {
        el.setAttribute("placeholder", translation);
      }
    });

    // Update Language selection dropdown in settings and header
    const langSelect = document.getElementById("select-ui-language");
    if (langSelect) {
      langSelect.value = this.getSavedPreference();
    }

    // Refresh dynamic badges and tabs if app is initialized
    if (window.onLanguageChanged && typeof window.onLanguageChanged === "function") {
      window.onLanguageChanged();
    }
  }
}

window.I18n = I18nManager;
